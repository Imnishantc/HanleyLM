from dataclasses import dataclass, asdict, field
from datetime import datetime
from typing import Optional, Dict, Any


@dataclass
class AttackResult:
    """
    Represents the output of an attack generated by AttackerAgent.
    """

    original_prompt: str
    attacked_prompt: str
    strategy: str
    success: bool

    model_response: Optional[str] = None
    execution_time: Optional[float] = None
    error: Optional[str] = None

    timestamp: str = field(
        default_factory=lambda: datetime.utcnow().isoformat()
    )

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    def __str__(self) -> str:
        return (
            f"\n"
            f"{'=' * 60}\n"
            f"Attack Strategy : {self.strategy}\n"
            f"Success         : {self.success}\n"
            f"Execution Time  : "
            f"{self.execution_time:.4f}s"
            if self.execution_time is not None
            else "\nExecution Time  : N/A"
        ) + (
            f"\nTimestamp       : {self.timestamp}\n"
            f"{'-' * 60}\n"
            f"Original Prompt:\n"
            f"{self.original_prompt}\n\n"
            f"Attacked Prompt:\n"
            f"{self.attacked_prompt}\n"
            f"{'-' * 60}\n"
            f"Model Response:\n"
            f"{self.model_response if self.model_response else 'N/A'}\n"
            f"{'-' * 60}\n"
            f"Error:\n"
            f"{self.error if self.error else 'None'}\n"
            f"{'=' * 60}"
        )